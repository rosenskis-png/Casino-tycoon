export interface EmojiDef {
  e: string;
  name: string;
  cat: EmojiCat;
  /** Main color (hex) and its color tag. */
  color: string;
  hue: string;
  clout: number;
  /** Tag → strength (1 core, 0.5 loose). */
  tags: Record<string, number>;
}

/** A color's tag: red, orange, yellow, green, blue, purple, pink, brown, white, grey or black. */
export function hueOf(hex: string): string {
  const n = parseInt(hex.slice(1), 16), r = (n >> 16) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  if (s < 0.2 || d < 0.12) return l > 0.75 ? "white" : l > 0.3 ? "grey" : "black";
  let h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
  h = (h * 60 + 360) % 360;
  if (h < 15 || h >= 345) return l > 0.7 ? "pink" : "red";
  if (h < 42) return l < 0.45 ? "brown" : "orange";
  if (h < 68) return l < 0.4 ? "brown" : "yellow";
  if (h < 165) return "green";
  if (h < 250) return "blue";
  if (h < 290) return "purple";
  return "pink";
}

function build(): Record<string, EmojiDef> {
  const out: Record<string, EmojiDef> = {};
  const groups: [EmojiCat, Row[]][] = [["animals", ANIMALS], ["sea", SEA], ["nature", NATURE], ["food", FOOD], ["drinks", DRINKS], ["people", PEOPLE], ["places", PLACES], ["things", THINGS], ["games", GAMES]];
  for (const [cat, rows] of groups) for (const [e, name, color, clout, t] of rows) {
    const tags: Record<string, number> = {};
    for (const w of t.split(" ")) if (w) tags[w.replace("~", "")] = w.endsWith("~") ? 0.5 : 1;
    const hue = hueOf(color);
    tags[`c_${hue}`] = 0.5;
    out[e] = { e, name, cat, color, hue, clout, tags };
  }
  return out;
}
